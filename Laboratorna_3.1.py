n = int(input("Введіть кількість елементів: "))            # зчитує кількість елементів і перетворює в ціле число
a = list(map(int, input("Введіть елементи масиву: ").split()))  # зчитуєм рядок, ділимо по пробілах, кожне число перетворюємо в int, складаємо в список

mn = a[0]                         # вважаємо, що перший елемент найменший
for x in a:                       # перебираємо всі елементи масиву
    if x < mn:                    # якщо поточний елемент менший за знайдений мінімум
        mn = x                    # запам'ятовуємо його як новий мінімум

k = 0                             # лічильник входжень мінімуму, спочатку 0
for x in a:                       # знову перебираємо всі елементи
    if x == mn:                   # якщо елемент дорівнює мінімуму
        k += 1                    # збільшуємо лічильник на 1

print("Найменше число:", mn)      # виводимо найменше число
print("Зустрічається разів:", k)  # виводимо, скільки разів воно зустрічається

for i in range(n - 1, n - k - 1, -1):  # індекси з кінця: від n-1 вниз до n-k (рівно k елементів)
    a[i] = mn                     # замінюємо елемент на найменше число

print("Змінений масив:", *a)      # виводимо змінений масив через пробіл