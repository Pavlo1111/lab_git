n = int(input("Введіть чотиризначне число: "))
# input() - просить користувача ввести текст з клавіатури
# int() - перетворює цей текст на ціле число

if 1000 <= abs(n) <= 9999:
    # abs(n) - модуль числа (відкидає мінус, -1234 стане 1234)
    # 1000 <= ... <= 9999 - перевірка, що число в межах чотиризначних
    n = abs(n)

    a = n // 1000          # перша цифра
    b = n // 100 % 10      # друга цифра
    c = n // 10 % 10       # третя цифра
    d = n % 10             # четверта цифра

    if a + b == c + d:
        # == перевіряє, чи ліва частина дорівнює правій
        print("Так, сума перших двох цифр дорівнює сумі двох останніх")
    else:
        print("Ні, суми не рівні")
else:
    print("Це не чотиризначне число")