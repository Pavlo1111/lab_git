e = 2.718281828459045    # число e задаємо вручну

a = float(input("Введіть a: "))        # початок проміжку
b = float(input("Введіть b: "))        # кінець проміжку
h = float(input("Введіть крок h: "))   # крок (має бути більше 0)

suma = 0      # сума підходящих значень y
kilkist = 0   # скільки значень y підійшло під умову 5 < y < 10

print("   x        y")
x = a
while x <= b + 1e-9:
    # 1e-9 - маленька поправка, щоб через неточність дробових чисел не загубити точку b
    y = x ** 2 + e ** x - 2 * x     # e ** x це e в степені x
    print(f"{x:8.3f} {y:10.4f}")

    if 5 < y < 10:
        suma = suma + y
        kilkist = kilkist + 1

    x = x + h    # наступний x

if kilkist > 0:
    print("Середнє арифметичне:", suma / kilkist)
else:
    print("Немає значень y, для яких 5 < y < 10")